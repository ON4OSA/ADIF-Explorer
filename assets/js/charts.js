/* ---------------------------------------------------------------------------
   ADIF Explorer — breakdown charts.

   Renders the loaded log as a set of linked part-to-whole charts (pie or
   ranked bars, chosen per card). No charting library: the geometry is a dozen
   lines and the page stays dependency-free.

   The charts cross-filter each other. Clicking a value selects it: the chart
   it belongs to keeps showing every value with the unselected ones dimmed,
   and every other chart re-decomposes the matching QSOs only. Selections in
   different dimensions combine, so Mode=SSB plus Band=20m shows SSB on 20m.

   Every distinct value gets its own slice - nothing is folded into "Other".
   --------------------------------------------------------------------------- */

(function (global) {
  "use strict";

  /* The eight validated categorical slots, assigned in fixed order.
     Past eight there is no palette that stays reliably distinguishable, so
     the tail is generated by rotating hue at a fixed step - enough to
     separate neighbouring slices, with the legend and tooltip carrying the
     actual identity. */
  var SERIES = [
    "#2a78d6", // blue
    "#eb6834", // orange
    "#1baf7a", // aqua
    "#eda100", // yellow
    "#e87ba4", // magenta
    "#008300", // green
    "#4a3aa7", // violet
    "#e34948"  // red
  ];

  var SURFACE = "#ffffff";       // pane background: the slice separator color
  var LABEL_MIN_PCT = 8;         // below this a label would crowd its neighbours

  var CHARTS = [
    { key: "country",   title: "Country",      accessor: "country" },
    { key: "continent", title: "Continent",    accessor: "continent" },
    { key: "band",      title: "Band",         accessor: "band" },
    { key: "station",   title: "Station type", accessor: "stationType" },
    { key: "mode",      title: "Mode",         accessor: "mode" },
    { key: "operator",  title: "Operator",     accessor: "operator" }
  ];

  /* Chart types offered per card. The icons are inline so the selector needs
     no image requests and inherits colour from the button. */
  var TYPES = [
    {
      key: "pie",
      label: "Pie chart",
      icon: '<path d="M8 1.8a6.2 6.2 0 1 0 6.2 6.2"/><path d="M8 1.8V8h6.2A6.2 6.2 0 0 0 8 1.8z"/>'
    },
    {
      key: "bar",
      label: "Bar chart",
      icon: '<path d="M2.2 3.6h7.2M2.2 8h10.4M2.2 12.4h5.4"/>'
    }
  ];

  var DEFAULT_TYPE = "pie";

  /* Everything about the currently displayed log. Held at module scope so a
     filter click can redraw without re-reading or re-parsing the file. */
  var session = null;

  /* Counts are right-aligned in a column wide enough for the largest of them,
     so every row's value block is the same width. Without this each row is its
     own grid and a three-digit count steals that much width from its own bar,
     leaving the tracks visibly unequal. */
  function countWidth(data) {
    var largest = data.slices.length ? data.slices[0].count : 0;
    return Math.max(2, String(largest).length) + "ch";
  }

  function escapeHtml(value) {
    return String(value)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  /* Colour for the value ranked `index` in the UNFILTERED data. Filtering
     changes which values survive and in what order, so colours are looked up
     by value rather than by position - a filter must never repaint the
     categories that remain. */
  function colorFor(index) {
    if (index < SERIES.length) return SERIES[index];

    var step = index - SERIES.length;
    var hue = (step * 137.508) % 360;
    var light = step % 2 ? 62 : 44;
    return "hsl(" + hue.toFixed(1) + " 52% " + light + "%)";
  }

  /* --- aggregation -------------------------------------------------------- */

  /* Counts the given record indices by dimension, largest first. */
  function tallyIndices(indices, key) {
    var counts = Object.create(null);
    var values = session.values;
    var i;

    for (i = 0; i < indices.length; i++) {
      var value = values[indices[i]][key];
      counts[value] = (counts[value] || 0) + 1;
    }

    var slices = Object.keys(counts).map(function (name) {
      return { name: name, count: counts[name] };
    });

    slices.sort(function (a, b) {
      return b.count - a.count || a.name.localeCompare(b.name);
    });

    var total = indices.length;
    var colors = session.colors[key];

    slices.forEach(function (slice) {
      slice.pct = total ? (slice.count / total) * 100 : 0;
      slice.color = colors[slice.name] || SERIES[0];
    });

    return { slices: slices, total: total, distinct: slices.length };
  }

  /* Public helper: tallies raw records, used by tests and by the colour map. */
  function tally(records, accessor) {
    var counts = Object.create(null);
    var i;

    for (i = 0; i < records.length; i++) {
      var key = accessor(records[i]);
      counts[key] = (counts[key] || 0) + 1;
    }

    var slices = Object.keys(counts).map(function (name) {
      return { name: name, count: counts[name] };
    });

    slices.sort(function (a, b) {
      return b.count - a.count || a.name.localeCompare(b.name);
    });

    var total = records.length;
    slices.forEach(function (slice, index) {
      slice.pct = total ? (slice.count / total) * 100 : 0;
      slice.color = colorFor(index);
    });

    return { slices: slices, total: total, distinct: slices.length };
  }

  /* Record indices matching every active filter, optionally ignoring one
     dimension's own filter. A chart is drawn ignoring its own selection, so
     the other values stay visible and can be picked instead. */
  function matchingIndices(exceptKey) {
    var keys = Object.keys(session.filters).filter(function (key) {
      return key !== exceptKey;
    });

    var out = [];
    var values = session.values;

    for (var i = 0; i < values.length; i++) {
      var ok = true;
      for (var j = 0; j < keys.length; j++) {
        if (values[i][keys[j]] !== session.filters[keys[j]]) { ok = false; break; }
      }
      if (ok) out.push(i);
    }
    return out;
  }

  /* --- geometry ----------------------------------------------------------- */

  var CX = 100, CY = 100, R = 82;

  function point(angle, radius) {
    return [
      (CX + radius * Math.cos(angle)).toFixed(2),
      (CY + radius * Math.sin(angle)).toFixed(2)
    ];
  }

  function slicePath(start, end) {
    var large = end - start > Math.PI ? 1 : 0;
    var a = point(start, R);
    var b = point(end, R);
    return "M" + CX + "," + CY + " L" + a[0] + "," + a[1] +
           " A" + R + "," + R + " 0 " + large + " 1 " + b[0] + "," + b[1] + " Z";
  }

  /* --- rendering ---------------------------------------------------------- */

  /* Marks a slice against the chart's own selection: the picked one stays
     lit, everything else is dimmed. */
  function stateClass(chartKey, name) {
    var selected = session.filters[chartKey];
    if (selected === undefined) return "";
    return name === selected ? " is-selected" : " is-dimmed";
  }

  function renderPie(data, chartKey) {
    var html = [];
    var slices = data.slices;

    html.push('<svg class="pie__svg" viewBox="0 0 200 200" role="img" ' +
              'aria-label="Pie chart of ' + escapeHtml(data.title) + '">');

    if (slices.length === 1) {
      // A single slice is a full turn, which an arc path cannot express
      // (start and end coincide) - draw the circle instead.
      html.push('<circle class="pie__slice' + stateClass(chartKey, slices[0].name) +
                '" cx="' + CX + '" cy="' + CY + '" r="' + R + '" fill="' +
                slices[0].color + '" data-chart="' + chartKey + '" data-slice="0"/>');
    } else {
      var angle = -Math.PI / 2;   // start at 12 o'clock
      slices.forEach(function (slice, index) {
        var sweep = (slice.count / data.total) * Math.PI * 2;
        var end = angle + sweep;

        html.push('<path class="pie__slice' + stateClass(chartKey, slice.name) +
                  '" d="' + slicePath(angle, end) + '" ' +
                  'fill="' + slice.color + '" stroke="' + SURFACE +
                  '" stroke-width="1.5" stroke-linejoin="round" ' +
                  'data-chart="' + chartKey + '" data-slice="' + index + '"/>');
        angle = end;
      });
    }

    // Direct labels, selectively: only slices with room for the text. The
    // tooltip covers the rest.
    var labelAngle = -Math.PI / 2;
    slices.forEach(function (slice) {
      var sweep = (slice.count / data.total) * Math.PI * 2;
      var mid = labelAngle + sweep / 2;
      labelAngle += sweep;

      if (slice.pct < LABEL_MIN_PCT) return;
      var at = point(mid, R * 0.64);
      html.push('<text class="pie__label" x="' + at[0] + '" y="' + at[1] +
                '" text-anchor="middle" dominant-baseline="central">' +
                Math.round(slice.pct) + "%</text>");
    });

    html.push("</svg>");
    return html.join("");
  }

  function renderLegend(data, chartKey) {
    var html = ['<ul class="pie__legend" style="--count-width:' +
                countWidth(data) + '">'];

    data.slices.forEach(function (slice, index) {
      html.push('<li class="pie__legend-item' + stateClass(chartKey, slice.name) +
                '" data-chart="' + chartKey + '" data-slice="' + index +
                '" role="button" tabindex="0" aria-pressed="' +
                (session.filters[chartKey] === slice.name) + '">');
      html.push('<span class="pie__swatch" style="background:' + slice.color + '"></span>');
      html.push('<span class="pie__legend-name" title="' + escapeHtml(slice.name) + '">' +
                escapeHtml(slice.name) + "</span>");
      html.push('<span class="pie__legend-value">' +
                '<span class="pie__legend-count">' + slice.count + "</span>" +
                '<span class="pie__legend-pct">' + slice.pct.toFixed(1) + "%</span></span>");
      html.push("</li>");
    });

    html.push("</ul>");
    return html.join("");
  }

  /* Ranked horizontal bars. Bars are measured against the largest value, not
     the total, so the leader fills the track and the rest read against it.
     One hue throughout: the row label carries identity, so colouring dozens of
     bars separately would add noise without adding information. */
  function renderBars(data, chartKey) {
    var max = data.slices.length ? data.slices[0].count : 0;
    var html = ['<div class="bar-chart" style="--count-width:' +
                countWidth(data) + '">'];

    data.slices.forEach(function (slice, index) {
      var width = max ? (slice.count / max) * 100 : 0;

      html.push('<div class="bar-chart__row' + stateClass(chartKey, slice.name) +
                '" data-chart="' + chartKey + '" data-slice="' + index +
                '" role="button" tabindex="0" aria-pressed="' +
                (session.filters[chartKey] === slice.name) + '">');
      html.push('<span class="bar-chart__label" title="' + escapeHtml(slice.name) + '">' +
                escapeHtml(slice.name) + "</span>");
      html.push('<span class="bar-chart__track"><span class="bar-chart__fill" style="width:' +
                width.toFixed(2) + '%"></span></span>');
      html.push('<span class="bar-chart__value">' +
                '<span class="bar-chart__count">' + slice.count + "</span>" +
                '<span class="bar-chart__pct">' + slice.pct.toFixed(1) + "%</span></span>");
      html.push("</div>");
    });

    html.push("</div>");
    return html.join("");
  }

  function renderToggle(chartKey, active) {
    var html = ['<div class="chart-toggle" role="group" aria-label="Chart type">'];

    TYPES.forEach(function (type) {
      var pressed = type.key === active;
      html.push('<button class="chart-toggle__btn" type="button" ' +
                'data-chart-type="' + type.key + '" data-for="' + chartKey + '" ' +
                'aria-pressed="' + pressed + '" ' +
                'title="' + type.label + '" aria-label="' + type.label + '">' +
                '<svg viewBox="0 0 16 16" width="14" height="14" fill="none" ' +
                'stroke="currentColor" stroke-width="1.4" stroke-linecap="round" ' +
                'stroke-linejoin="round" aria-hidden="true">' + type.icon + "</svg></button>");
    });

    html.push("</div>");
    return html.join("");
  }

  /* The part of a card that changes when the type or the filters change. */
  function renderBody(data, chartKey, type) {
    if (type === "bar") {
      return '<div class="chart-card__body chart-card__body--bar">' +
             renderBars(data, chartKey) + "</div>";
    }

    return '<div class="chart-card__body chart-card__body--pie">' +
           renderPie(data, chartKey) + renderLegend(data, chartKey) + "</div>";
  }

  function renderCard(spec) {
    // Drawn ignoring this chart's own selection, so its other values stay on
    // screen (dimmed) and can be picked instead of it.
    var data = tallyIndices(matchingIndices(spec.key), spec.key);
    data.title = spec.title;

    var type = session.types[spec.key] || DEFAULT_TYPE;
    session.types[spec.key] = type;

    // A dimension with a long tail needs a row of its own; otherwise its
    // height drags every card beside it down.
    var wide = data.distinct > 12 ? " chart-card--wide" : "";
    var filtered = session.filters[spec.key] !== undefined ? " chart-card--filtered" : "";

    var html = ['<section class="chart-card' + wide + filtered +
                '" data-chart="' + spec.key + '">'];

    html.push('<div class="chart-card__head"><div>');
    html.push('<h2 class="chart-card__title">' + escapeHtml(spec.title) + "</h2>");
    if (data.total) {
      html.push('<p class="chart-card__sub">' + data.distinct + " distinct · " +
                data.total.toLocaleString() + " QSO" +
                (data.total === 1 ? "" : "s") + "</p>");
    }
    html.push("</div>");
    if (data.total) html.push(renderToggle(spec.key, type));
    html.push("</div>");

    if (!data.total) {
      html.push('<p class="chart-card__empty">No QSOs match</p></section>');
      return html.join("");
    }

    html.push(renderBody(data, spec.key, type));
    html.push("</section>");
    return html.join("");
  }

  /* The active selections, each removable, plus a clear-all. Without this a
     filter set from one card would be hard to find and undo from another. */
  function renderFilterBar() {
    var keys = Object.keys(session.filters);
    if (!keys.length) return "";

    var html = ['<div class="filter-bar"><span class="filter-bar__label">Filtered by</span>'];

    CHARTS.forEach(function (spec) {
      var value = session.filters[spec.key];
      if (value === undefined) return;

      html.push('<button class="filter-chip" type="button" data-clear="' + spec.key +
                '" title="Remove this filter">' +
                '<span class="filter-chip__dim">' + escapeHtml(spec.title) + "</span>" +
                '<span class="filter-chip__value">' + escapeHtml(value) + "</span>" +
                '<svg viewBox="0 0 16 16" width="11" height="11" fill="none" ' +
                'stroke="currentColor" stroke-width="1.8" stroke-linecap="round" ' +
                'aria-hidden="true"><path d="M4 4l8 8M12 4l-8 8"/></svg></button>');
    });

    html.push('<button class="filter-bar__clear" type="button" data-clear-all>Clear all</button>');
    html.push("</div>");
    return html.join("");
  }

  /* Redraws every card from the current filters. */
  function draw() {
    var matched = matchingIndices(null).length;
    var total = session.values.length;

    var html = ['<div class="chart-view">'];

    html.push('<div class="chart-view__meta"><strong>' + escapeHtml(session.fileName) +
              "</strong><span>" +
              (matched === total
                ? total.toLocaleString() + " record" + (total === 1 ? "" : "s")
                : matched.toLocaleString() + " of " + total.toLocaleString() + " records") +
              "</span></div>");

    html.push(renderFilterBar());
    html.push('<div class="chart-grid">');

    CHARTS.forEach(function (spec) {
      html.push(renderCard(spec));
    });

    html.push("</div></div>");
    session.pane.innerHTML = html.join("");

    attachInteraction(session.pane.querySelector(".chart-view"));
    attachTooltip(session.pane.querySelector(".chart-grid"));
  }

  /* --- interaction -------------------------------------------------------- */

  /* Selecting a value that is already selected clears it, so a second click
     on the same slice is the way back out. */
  function toggleFilter(chartKey, name) {
    if (session.filters[chartKey] === name) {
      delete session.filters[chartKey];
    } else {
      session.filters[chartKey] = name;
    }
    draw();
  }

  function sliceAt(target) {
    var key = target.getAttribute("data-chart");
    var index = parseInt(target.getAttribute("data-slice"), 10);
    if (!key || isNaN(index)) return null;

    var data = tallyIndices(matchingIndices(key), key);
    return data.slices[index] ? { key: key, slice: data.slices[index] } : null;
  }

  /* Bound to the view's own root, which draw() rebuilds every time, NOT to the
     work pane. The pane outlives the view and is shared with the time view,
     which emits the same data-clear / data-clear-all attributes on its filter
     bar: a listener left on the pane would keep firing while the other view is
     on screen, clear the wrong filter set and repaint over it. Listeners on the
     root die with the element, so there is exactly one live handler at a time
     and no cross-talk is possible. */
  function attachInteraction(root) {
    if (!root) return;

    root.addEventListener("click", function (event) {
      var chip = event.target.closest("[data-clear], [data-clear-all]");
      if (chip && root.contains(chip)) {
        if (chip.hasAttribute("data-clear-all")) {
          session.filters = Object.create(null);
        } else {
          delete session.filters[chip.getAttribute("data-clear")];
        }
        draw();
        return;
      }

      var typeButton = event.target.closest("[data-chart-type]");
      if (typeButton && root.contains(typeButton)) {
        var forKey = typeButton.getAttribute("data-for");
        var type = typeButton.getAttribute("data-chart-type");
        if (session.types[forKey] !== type) {
          session.types[forKey] = type;
          draw();
        }
        return;
      }

      var mark = event.target.closest("[data-slice]");
      if (!mark || !root.contains(mark)) return;

      var hit = sliceAt(mark);
      if (hit) toggleFilter(hit.key, hit.slice.name);
    });

    // Legend rows and bar rows are exposed as buttons, so they answer the
    // keyboard too. Pie slices stay mouse-only; the legend beside them is the
    // keyboard route to the same values.
    root.addEventListener("keydown", function (event) {
      if (event.key !== "Enter" && event.key !== " ") return;

      var mark = event.target.closest('[data-slice][role="button"]');
      if (!mark || !root.contains(mark)) return;

      event.preventDefault();
      var hit = sliceAt(mark);
      if (hit) toggleFilter(hit.key, hit.slice.name);
    });
  }

  /* --- hover tooltip ------------------------------------------------------ */

  /* One tooltip serves every chart. Slices and legend rows share the same
     data-chart/data-slice pair, so hovering either one resolves to the same
     entry and highlights its partner. */
  function attachTooltip(root) {
    if (!root) return;

    var tip = document.createElement("div");
    tip.className = "chart-tip";
    tip.hidden = true;
    root.appendChild(tip);

    function show(event) {
      var target = event.target.closest("[data-slice]");
      if (!target || !root.contains(target)) return;

      var hit = sliceAt(target);
      if (!hit) return;

      var index = target.getAttribute("data-slice");

      tip.innerHTML =
        '<span class="chart-tip__swatch" style="background:' + hit.slice.color + '"></span>' +
        '<span class="chart-tip__name">' + escapeHtml(hit.slice.name) + "</span>" +
        '<span class="chart-tip__value">' + hit.slice.count + " · " +
        hit.slice.pct.toFixed(1) + "%</span>";
      tip.hidden = false;

      root.querySelectorAll(".is-active").forEach(function (el) {
        el.classList.remove("is-active");
      });
      root.querySelectorAll('[data-chart="' + hit.key + '"][data-slice="' + index + '"]')
          .forEach(function (el) { el.classList.add("is-active"); });

      position(event);
    }

    function position(event) {
      if (tip.hidden) return;

      var pad = 14;
      var box = tip.getBoundingClientRect();
      var x = event.clientX + pad;
      var y = event.clientY + pad;

      // Keep the tooltip on screen near the edges.
      if (x + box.width > window.innerWidth - 8) x = event.clientX - box.width - pad;
      if (y + box.height > window.innerHeight - 8) y = event.clientY - box.height - pad;

      tip.style.left = Math.max(8, x) + "px";
      tip.style.top = Math.max(8, y) + "px";
    }

    function hide(event) {
      if (event && event.relatedTarget && event.relatedTarget.closest &&
          event.relatedTarget.closest("[data-slice]")) return;
      tip.hidden = true;
      root.querySelectorAll(".is-active").forEach(function (el) {
        el.classList.remove("is-active");
      });
    }

    root.addEventListener("mouseover", show);
    root.addEventListener("mousemove", position);
    root.addEventListener("mouseout", hide);
    root.addEventListener("mouseleave", hide);
  }

  /* --- entry point -------------------------------------------------------- */

  /* Precomputes each record's value in every dimension once, so filtering and
     re-tallying on each click are cheap. */
  function computeValues(records) {
    return records.map(function (record) {
      var row = {};
      CHARTS.forEach(function (spec) {
        row[spec.key] = AdifParser[spec.accessor](record);
      });
      return row;
    });
  }

  /* Colours are fixed here, from the unfiltered ranking, and looked up by
     value thereafter - so filtering never repaints a surviving category. */
  function computeColors(records) {
    var colors = Object.create(null);

    CHARTS.forEach(function (spec) {
      var map = Object.create(null);
      tally(records, AdifParser[spec.accessor]).slices.forEach(function (slice, index) {
        map[slice.name] = colorFor(index);
      });
      colors[spec.key] = map;
    });

    return colors;
  }

  function render(pane, log, fileName) {
    var records = log.records;

    if (!records.length) {
      pane.innerHTML = '<div class="placeholder"><p class="placeholder__text ' +
        'placeholder__text--error">No records to chart.</p></div>';
      return;
    }

    // Returning to the charts from the table keeps the filters and the chart
    // types; loading a different log starts clean.
    var sameLog = session && session.records === records;

    session = {
      pane: pane,
      records: records,
      fileName: fileName,
      values: sameLog ? session.values : computeValues(records),
      colors: sameLog ? session.colors : computeColors(records),
      filters: sameLog ? session.filters : Object.create(null),
      types: sameLog ? session.types : Object.create(null)
    };

    draw();
  }

  global.AdifCharts = {
    render: render,
    tally: tally,
    colorFor: colorFor,
    /* The dimensions every view breaks the log down by. Shared so the time
       view stays in step with this one: adding an entry here adds it there. */
    dimensions: CHARTS,
    /* exposed for tests */
    state: function () { return session; }
  };
})(window);
